// CompleteScanCycle marks a running cycle whose units are all completed as
// completed, then returns the cycle.
func (ss *SystemStore) CompleteScanCycle(ctx context.Context, cycleID string) (ScanCycleRecord, error) {
	now := sqliteTimestamp(time.Now())
	tx, err := ss.store.DB.BeginTx(ctx, nil)
	if err != nil {
		return ScanCycleRecord{}, err
	}
	defer tx.Rollback()
	var status string
	var completed, total int
	if err = tx.QueryRowContext(ctx, `SELECT status,completed_units,total_units FROM scan_cycles WHERE id=?`, cycleID).Scan(&status, &completed, &total); err != nil {
		if errors.Is(err, sql.ErrNoRows) {
			return ScanCycleRecord{}, fmt.Errorf("%w: %s", ErrNoScanCycle, cycleID)
		}
		return ScanCycleRecord{}, err
	}
	if status == "completed" {
		_ = tx.Rollback()
		return ss.scanCycle(ctx, cycleID)
	}
	if status != "running" {
		return ScanCycleRecord{}, ErrCycleNotResumable
	}
	if completed != total {
		return ScanCycleRecord{}, fmt.Errorf("%w: %d of %d units completed", ErrCycleIncomplete, completed, total)
	}
	// Keep the completed unit payloads until the merged scan is promoted. The
	// promotion is a separate transaction, and retaining this short-lived
	// recovery source means a process crash between these operations cannot lose
	// a completed cycle. SaveScan/FinalizeManagedScan reclaim the payloads after
	// the immutable scan and its indexes are committed.
	if _, err = tx.ExecContext(ctx, `UPDATE scan_cycles SET status='completed',updated_at=?,finished_at=?,last_error='' WHERE id=? AND status='running'`, now, now, cycleID); err != nil {
		return ScanCycleRecord{}, err
	}
	if err = tx.Commit(); err != nil {
		return ScanCycleRecord{}, err
	}
	return ss.scanCycle(ctx, cycleID)
}

// tenantScanCycleSQL selects the ID of one cycle if it belongs to a tenant.
// Its arguments are the tenant ID and the cycle ID.
const tenantScanCycleSQL = `SELECT c.id FROM scan_cycles c JOIN jobs j ON j.id=c.job_id AND j.tenant_id=? WHERE c.id=?`

// DiscardScanCycle discards one of the tenant's active cycles, or a
// completed one whose scan was not promoted, and deletes its units. A cycle
// of another tenant is ErrNoScanCycle, like an unknown ID, and is left
// unchanged. A running cycle whose job holds a live lease is refused with
// ErrJobScanActive.
func (ts *TenantStore) DiscardScanCycle(ctx context.Context, cycleID string) error {
	if err := ts.ready(); err != nil {
		return err
	}
	tx, err := ts.store.DB.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	var status, jobID string
	if err = tx.QueryRowContext(ctx, `SELECT c.status,c.job_id FROM scan_cycles c JOIN jobs j ON j.id=c.job_id AND j.tenant_id=? WHERE c.id=?`, ts.scope.id, cycleID).Scan(&status, &jobID); errors.Is(err, sql.ErrNoRows) {
		return ErrNoScanCycle
	} else if err != nil {
		return err
	}
	if status != "running" && status != "paused" && status != "stalled" && status != "completed" {
		return ErrCycleNotResumable
	}
	if status == "running" {
		var leased int
		if err := tx.QueryRowContext(ctx, `SELECT EXISTS(SELECT 1 FROM job_leases WHERE job=? AND expires_at>?)`, jobID, sqliteTimestamp(time.Now())).Scan(&leased); err != nil {
			return err
		}
		if leased != 0 {
			return ErrJobScanActive
		}
	}
	if status == "completed" {
		var promoted int
		if err := tx.QueryRowContext(ctx, scanCycleHasScanQuery, cycleID, ts.scope.id).Scan(&promoted); err != nil {
			return err
		}
		if promoted > 0 {
			return ErrCycleNotResumable
		}
	}
	stamp := sqliteTimestamp(time.Now())
	result, err := tx.ExecContext(ctx, `UPDATE scan_cycles SET status='discarded',updated_at=?,finished_at=?,last_error='discarded by administrator',completed_units=0,total_units=0,completed_probes=0,total_probes=0 WHERE id=? AND status IN ('running','paused','stalled','completed') AND id IN (`+tenantScanCycleSQL+`)`, stamp, stamp, cycleID, ts.scope.id, cycleID)
	if err != nil {
		return err
	}
	updated, err := result.RowsAffected()
	if err != nil {
		return err
	}
	if updated != 1 {
		return ErrCycleNotResumable
	}
	if _, err = tx.ExecContext(ctx, `DELETE FROM scan_cycle_units WHERE cycle_id=? AND cycle_id IN (`+tenantScanCycleSQL+`)`, cycleID, ts.scope.id, cycleID); err != nil {
		return err
	}
	return tx.Commit()
}

// ExpireScanCycles ends every tenant's active cycles whose resume window has
// elapsed at now, in bounded batches, except those whose job holds a live
// lease, and returns how many it ended.
func (ss *SystemStore) ExpireScanCycles(ctx context.Context, now time.Time) (int64, error) {
	if now.IsZero() {
		now = time.Now().UTC()
	}
	stamp := sqliteTimestamp(now)
	var total int64
	for {
		if err := ctx.Err(); err != nil {
			return total, err
		}
		tx, err := ss.store.DB.BeginTx(ctx, nil)
		if err != nil {
			return total, err
		}
		ids, err := expiredScanCycleIDs(ctx, tx, stamp)
		if err != nil {
			_ = tx.Rollback()
			return total, err
		}
		if len(ids) == 0 {
			if err := tx.Commit(); err != nil {
				return total, err
			}
			return total, nil
		}
		placeholders := make([]string, len(ids))
		args := []any{stamp, stamp}
		for i, id := range ids {
			placeholders[i] = "?"
			args = append(args, id)
		}
		query := `UPDATE scan_cycles SET status='expired',updated_at=?,finished_at=?,last_error='scan cycle exceeded its resume window' WHERE status IN ('running','paused','stalled') AND id IN (` + strings.Join(placeholders, ",") + `)`
		result, err := tx.ExecContext(ctx, query, args...)
		if err != nil {
			_ = tx.Rollback()
			return total, err
		}
		changed, _ := result.RowsAffected()
		if err := tx.Commit(); err != nil {
			return total, err
		}
		total += changed
		if err := ss.clearExpiredCyclePayloads(ctx, ids); err != nil {
			return total, err
		}
	}
}

// ExpireScanCycle ends one active cycle whose resume window has elapsed at
// now and returns the cycle's current record. ExpireScanCycles skips a cycle
// whose job holds a live lease, so the scan that holds the lease uses this to
// record the expiry on its own trigger. A cycle that is still inside its
// window, or that is no longer active, is returned unchanged.
func (ss *SystemStore) ExpireScanCycle(ctx context.Context, cycleID string, now time.Time) (ScanCycleRecord, error) {
	stamp := sqliteTimestamp(now)
	result, err := ss.store.DB.ExecContext(ctx, `UPDATE scan_cycles SET status='expired',updated_at=?,finished_at=?,last_error='scan cycle exceeded its resume window' WHERE id=? AND status IN ('running','paused','stalled') AND expires_at<=?`, stamp, stamp, cycleID, stamp)
	if err != nil {
		return ScanCycleRecord{}, err
	}
	if changed, _ := result.RowsAffected(); changed == 1 {
		// The terminal state is already durable. As in StartScanCycleAttempt,
		// payload cleanup is best effort and the retention pass finishes it.
		_ = ss.clearExpiredCyclePayloads(ctx, []string{cycleID})
	}
	return ss.scanCycle(ctx, cycleID)
}

func expiredScanCycleIDs(ctx context.Context, tx *sql.Tx, stamp string) ([]string, error) {
	// A cycle with a live job lease is still being worked, even if its resume
	// window has elapsed. The scan owner renews its lease through finalization;
	// excluding it here prevents housekeeping from racing that final commit.
	rows, err := tx.QueryContext(ctx, `SELECT c.id FROM scan_cycles AS c WHERE c.status IN ('running','paused','stalled') AND c.expires_at<=? AND NOT EXISTS (SELECT 1 FROM job_leases AS l WHERE l.job=c.job_id AND l.expires_at>?) ORDER BY c.expires_at,c.id LIMIT ?`, stamp, stamp, scanCycleReconcileBatchSize)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	ids := make([]string, 0, scanCycleReconcileBatchSize)
	for rows.Next() {
		var id string
		if err := rows.Scan(&id); err != nil {
			return nil, err
		}
		ids = append(ids, id)
	}
	return ids, rows.Err()
}

// clearExpiredCyclePayloads reclaims potentially large checkpoint documents
// after the terminal cycle transition. The cycle IDs are already bounded by
// ExpireScanCycles; each update is additionally limited to one batch of unit
// rows so a single broad cycle cannot monopolize the writer connection.
func (ss *SystemStore) clearExpiredCyclePayloads(ctx context.Context, ids []string) error {
	if len(ids) == 0 {
		return nil
	}
	placeholders := make([]string, len(ids))
	args := make([]any, len(ids))
	for i, id := range ids {
		placeholders[i] = "?"
		args[i] = id
	}
	args = append(args, scanCycleReconcileBatchSize)
	query := `UPDATE scan_cycle_units SET snapshot_json='{}',last_error='cycle expired' WHERE rowid IN (SELECT rowid FROM scan_cycle_units WHERE cycle_id IN (` + strings.Join(placeholders, ",") + `) AND snapshot_json<>'{}' ORDER BY rowid LIMIT ?)`
	for {
		if err := ctx.Err(); err != nil {
			return err
		}
		result, err := ss.store.DB.ExecContext(ctx, query, args...)
		if err != nil {
			return err
		}
		count, _ := result.RowsAffected()
		if count < scanCycleReconcileBatchSize {
			return nil
		}
	}
}

// LoadScanCycleFragments returns a cycle's pinned plan and the checkpoint of
// every completed unit, in order, to merge into the cycle's scan. A reclaimed
// checkpoint is ErrMissingCheckpoint.
func (ss *SystemStore) LoadScanCycleFragments(ctx context.Context, cycleID string) (scanner.WorkPlan, []model.Snapshot, error) {
	plan, err := ss.scanCyclePlan(ctx, cycleID)
	if err != nil {
		return scanner.WorkPlan{}, nil, err
	}
	rows, err := ss.store.reader().QueryContext(ctx, `SELECT sequence,snapshot_json FROM scan_cycle_units WHERE cycle_id=? AND status='completed' ORDER BY sequence`, cycleID)
	if err != nil {
		return scanner.WorkPlan{}, nil, err
	}
	defer rows.Close()
	var fragments []model.Snapshot
	for rows.Next() {
		var sequence int
		var raw []byte
		if err = rows.Scan(&sequence, &raw); err != nil {
			return scanner.WorkPlan{}, nil, err
		}
		// '{}' is the durable sentinel used after a promoted or expired cycle's
		// large payload has been reclaimed.  Treat it as missing during recovery;
		// unmarshalling it into an empty Snapshot would otherwise look like a
		// valid zero-result fragment and could establish an empty baseline.
		trimmed := strings.TrimSpace(string(raw))
		if trimmed == "" || trimmed == "{}" || trimmed == "null" {
			return scanner.WorkPlan{}, nil, fmt.Errorf("%w: cycle %s sequence %d", ErrMissingCheckpoint, cycleID, sequence)
		}
		var snapshot model.Snapshot
		if err = json.Unmarshal(raw, &snapshot); err != nil {
			return scanner.WorkPlan{}, nil, err
		}
		fragments = append(fragments, snapshot)
	}
	return plan, fragments, rows.Err()
}

func trimCycleError(raw string) string {
	raw = strings.TrimSpace(raw)
	if len(raw) > 500 {
		return raw[:500] + "…"
	}
	return raw
}
