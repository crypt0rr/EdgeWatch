func (s *Store) SplitScanCycleUnit(ctx context.Context, cycleID string, sequence int, first, second scanner.WorkUnit, lastError string) error {
	firstRaw, err := json.Marshal(first)
	if err != nil {
		return err
	}
	secondRaw, err := json.Marshal(second)
	if err != nil {
		return err
	}
	tx, err := s.DB.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	var status string
	var originalRaw []byte
	if err = tx.QueryRowContext(ctx, `SELECT status,work_unit_json FROM scan_cycle_units WHERE cycle_id=? AND sequence=?`, cycleID, sequence).Scan(&status, &originalRaw); err != nil {
		return err
	}
	if status == "completed" {
		return nil
	}
	if status != "running" {
		return ErrCycleNotResumable
	}
	var cycleStatus string
	if err = tx.QueryRowContext(ctx, `SELECT status FROM scan_cycles WHERE id=?`, cycleID).Scan(&cycleStatus); err != nil {
		if errors.Is(err, sql.ErrNoRows) {
			return fmt.Errorf("%w: %s", ErrNoScanCycle, cycleID)
		}
		return err
	}
	if cycleStatus != "running" {
		return ErrCycleNotResumable
	}
	var original scanner.WorkUnit
	if err := json.Unmarshal(originalRaw, &original); err != nil {
		return err
	}
	var next int
	if err = tx.QueryRowContext(ctx, `SELECT COALESCE(MAX(sequence),-1)+1 FROM scan_cycle_units WHERE cycle_id=?`, cycleID).Scan(&next); err != nil {
		return err
	}
	second.Sequence = next
	secondRaw, err = json.Marshal(second)
	if err != nil {
		return err
	}
	if _, err = tx.ExecContext(ctx, `UPDATE scan_cycle_units SET work_unit_json=?,identity=?,status='pending',last_error=? WHERE cycle_id=? AND sequence=?`, firstRaw, scanCycleUnitIdentity(first), trimCycleError(lastError), cycleID, sequence); err != nil {
		return err
	}
	if _, err = tx.ExecContext(ctx, `INSERT INTO scan_cycle_units(cycle_id,sequence,work_unit_json,identity,status,attempts,snapshot_json,started_at,finished_at,last_error) VALUES(?,?,?,?,?,?,?,?,?,?)`, cycleID, next, secondRaw, scanCycleUnitIdentity(second), "pending", 0, []byte(`{}`), "", "", ""); err != nil {
		return err
	}
	probeDelta := first.Probes + second.Probes - original.Probes
	cycleUpdate, err := tx.ExecContext(ctx, `UPDATE scan_cycles SET total_units=total_units+1,total_probes=total_probes+?,updated_at=?,last_error=? WHERE id=? AND status='running'`, probeDelta, time.Now().UTC().Format(time.RFC3339Nano), trimCycleError(lastError), cycleID)
	if err != nil {
		return err
	}
	if count, _ := cycleUpdate.RowsAffected(); count != 1 {
		return ErrCycleNotResumable
	}
	return tx.Commit()
}

