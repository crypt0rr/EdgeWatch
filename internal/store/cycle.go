func (s *Store) ExpireScanCycles(ctx context.Context, now time.Time) (int64, error) {
	if now.IsZero() {
		now = time.Now().UTC()
	}
	stamp := now.UTC().Format(time.RFC3339Nano)
	var total int64
	for {
		if err := ctx.Err(); err != nil {
			return total, err
		}
		tx, err := s.DB.BeginTx(ctx, nil)
		if err != nil {
			return total, err
		}
		ids, err := expiredScanCycleIDs(ctx, tx, stamp)
		if err != nil {
			_ = tx.Rollback()
			return total, err
		}
		if len(ids) == 0 {
			if err := tx.Commit(); err != nil {
				return total, err
			}
			return total, nil
		}
		placeholders := make([]string, len(ids))
		args := []any{stamp, stamp}
		for i, id := range ids {
			placeholders[i] = "?"
			args = append(args, id)
		}
		query := `UPDATE scan_cycles SET status='expired',updated_at=?,finished_at=?,last_error='scan cycle exceeded its resume window' WHERE status IN ('running','paused','stalled') AND id IN (` + strings.Join(placeholders, ",") + `)`
		result, err := tx.ExecContext(ctx, query, args...)
		if err != nil {
			_ = tx.Rollback()
			return total, err
		}
		changed, _ := result.RowsAffected()
		if err := tx.Commit(); err != nil {
			return total, err
		}
		total += changed
		if err := s.clearExpiredCyclePayloads(ctx, ids); err != nil {
			return total, err
		}
	}
}

func expiredScanCycleIDs(ctx context.Context, tx *sql.Tx, stamp string) ([]string, error) {
	rows, err := tx.QueryContext(ctx, `SELECT id FROM scan_cycles WHERE status IN ('running','paused','stalled') AND expires_at<=? ORDER BY expires_at,id LIMIT ?`, stamp, scanCycleReconcileBatchSize)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	ids := make([]string, 0, scanCycleReconcileBatchSize)
	for rows.Next() {
		var id string
		if err := rows.Scan(&id); err != nil {
			return nil, err
		}
		ids = append(ids, id)
	}
	return ids, rows.Err()
}

// clearExpiredCyclePayloads reclaims potentially large checkpoint documents
// after the terminal cycle transition. The cycle IDs are already bounded by
// ExpireScanCycles; each update is additionally limited to one batch of unit
// rows so a single broad cycle cannot monopolize the writer connection.
func (s *Store) clearExpiredCyclePayloads(ctx context.Context, ids []string) error {
	if len(ids) == 0 {
		return nil
	}
	placeholders := make([]string, len(ids))
	args := make([]any, len(ids))
	for i, id := range ids {
		placeholders[i] = "?"
		args[i] = id
	}
	args = append(args, scanCycleReconcileBatchSize)
	query := `UPDATE scan_cycle_units SET snapshot_json='{}',last_error='cycle expired' WHERE rowid IN (SELECT rowid FROM scan_cycle_units WHERE cycle_id IN (` + strings.Join(placeholders, ",") + `) AND snapshot_json<>'{}' ORDER BY rowid LIMIT ?)`
	for {
		if err := ctx.Err(); err != nil {
			return err
		}
		result, err := s.DB.ExecContext(ctx, query, args...)
		if err != nil {
			return err
		}
		count, _ := result.RowsAffected()
		if count < scanCycleReconcileBatchSize {
			return nil
		}
	}
}

func (s *Store) LoadScanCycleFragments(ctx context.Context, cycleID string) (scanner.WorkPlan, []model.Snapshot, error) {
	cycle, err := s.GetScanCycle(ctx, cycleID)
	if err != nil {
		return scanner.WorkPlan{}, nil, err
	}
	rows, err := s.reader().QueryContext(ctx, `SELECT snapshot_json FROM scan_cycle_units WHERE cycle_id=? AND status='completed' ORDER BY sequence`, cycleID)
	if err != nil {
		return scanner.WorkPlan{}, nil, err
	}
	defer rows.Close()
	var fragments []model.Snapshot
	for rows.Next() {
		var raw []byte
		if err = rows.Scan(&raw); err != nil {
			return scanner.WorkPlan{}, nil, err
		}
		var snapshot model.Snapshot
		if err = json.Unmarshal(raw, &snapshot); err != nil {
			return scanner.WorkPlan{}, nil, err
		}
		fragments = append(fragments, snapshot)
	}
	return cycle.Plan, fragments, rows.Err()
}

func trimCycleError(raw string) string {
	raw = strings.TrimSpace(raw)
	if len(raw) > 500 {
		return raw[:500] + "…"
	}
	return raw
}
