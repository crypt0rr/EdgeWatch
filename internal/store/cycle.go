var (
	// ErrNoScanCycle reports an unknown scan cycle, or one of another
	// tenant. It matches ErrNotFound, and its message is still "scan cycle
	// not found".
	ErrNoScanCycle       = fmt.Errorf("scan cycle %w", ErrNotFound)
	ErrNoPendingUnit     = errors.New("scan cycle has no pending work")
	ErrCycleNotResumable = errors.New("scan cycle is not resumable")
	ErrCycleIncomplete   = errors.New("scan cycle is incomplete")
	ErrMissingCheckpoint = errors.New("scan cycle checkpoint is missing")
)

// scanCycleReconcileBatchSize bounds the amount of discovery evidence and
// dynamic work generated by one writer transaction. A full-range Naabu cycle
// can contain thousands of address batches; processing them in bounded
// chunks keeps the writer available to foreground scan/checkpoint writes.
const scanCycleReconcileBatchSize = 64

// ScanCycleRecord is the durable state for a complete scope scan that may
// require more than one attempt. The plan includes the normalized job and
// pinned DNS expansion so a resumed cycle never silently changes scope.
//
// A cycle read from the store carries only the plan's creation time, job, and
// totals: its targets, scopes, and DNS expansion, which grow with the scope,
// are read only where they are used, by LoadScanCycleFragments and the
// enrichment reconciliation. Its units are the rows of scan_cycle_units.
type ScanCycleRecord struct {
	ID                 string
	JobID              string
	Job                string
	JobRevision        int64
	ConfigHash         string
	ExecutionHash      string
	BaselineEpoch      int64
	Plan               scanner.WorkPlan
	Status             string
	AttemptCount       int
	NoProgressAttempts int
	TotalUnits         int
	CompletedUnits     int
	TotalProbes        int64
	CompletedProbes    int64
	StartedAt          time.Time
	UpdatedAt          time.Time
	ExpiresAt          time.Time
	FinishedAt         time.Time
	LastError          string
}

// ScanCycleSummary is the bounded active-cycle projection included in the
// polled job list. Unlike ScanCycleRecord it does not decode the potentially
// large pinned work plan.
type ScanCycleSummary struct {
	ID                 string
	JobID              string
	JobRevision        int64
	Status             string
	AttemptCount       int
	NoProgressAttempts int
	TotalUnits         int
	CompletedUnits     int
	TotalProbes        int64
	CompletedProbes    int64
	StartedAt          time.Time
	UpdatedAt          time.Time
	ExpiresAt          time.Time
	FinishedAt         time.Time
	LastError          string
}

// ScanCycleUnit is one independently persisted Nmap invocation.
type ScanCycleUnit struct {
	CycleID    string
	Sequence   int
	Unit       scanner.WorkUnit
	Status     string
	Attempts   int
	Failures   int
	Snapshot   model.Snapshot
	StartedAt  time.Time
	FinishedAt time.Time
	LastError  string
}

// ScanCycleUnitSummary is the safe progress view returned to the web console.
// It omits checkpoint payloads, which can be very large for a full-range job.
type ScanCycleUnitSummary struct {
	CycleID    string    `json:"cycle_id"`
	Sequence   int       `json:"sequence"`
	Engine     string    `json:"engine,omitempty"`
	Phase      string    `json:"phase,omitempty"`
	Protocol   string    `json:"protocol"`
	Family     int       `json:"family"`
	Ports      string    `json:"ports"`
	PortCount  int       `json:"port_count"`
	Addresses  int       `json:"addresses"`
	Probes     int64     `json:"probes"`
	Status     string    `json:"status"`
	Attempts   int       `json:"attempts"`
	Failures   int       `json:"failures"`
	StartedAt  time.Time `json:"started_at"`
	FinishedAt time.Time `json:"finished_at"`
	LastError  string    `json:"last_error,omitempty"`
}

// CreateScanCycle stores a new paused cycle with its planned units. It is
// the daemon's writer: the cycle belongs to its job's tenant, which the
// scan_cycles foreign key requires to exist.
func (ss *SystemStore) CreateScanCycle(ctx context.Context, cycle ScanCycleRecord) (ScanCycleRecord, error) {
	if cycle.JobID == "" || cycle.Job == "" {
		return ScanCycleRecord{}, errors.New("scan cycle job is required")
	}
	if len(cycle.Plan.Units) == 0 {
		return ScanCycleRecord{}, errors.New("scan cycle has no work units")
	}
	if cycle.ID == "" {
		cycle.ID = uuid.NewString()
	}
	now := cycle.StartedAt.UTC()
	if now.IsZero() {
		now = time.Now().UTC()
	}
	cycle.StartedAt = now
	if cycle.UpdatedAt.IsZero() {
		cycle.UpdatedAt = now
	}
	if cycle.ExpiresAt.IsZero() {
		cycle.ExpiresAt = now.Add(8 * 24 * time.Hour)
	}
	cycle.Status = "paused"
	cycle.TotalUnits = len(cycle.Plan.Units)
	// Treat the persisted unit list as the source of truth for progress. This
	// also keeps alternate scanners safe when they omit the aggregate totals in
	// their plan; a resumed cycle must never advertise zero work for non-empty
	// units or over-count probes after a split.
	var plannedProbes int64
	for _, unit := range cycle.Plan.Units {
		plannedProbes += unit.Probes
	}
	cycle.TotalProbes = plannedProbes
	cycle.Plan.TotalUnits = cycle.TotalUnits
	cycle.Plan.TotalProbes = plannedProbes
	// The units are stored once, as scan_cycle_units rows, and no reader of
	// plan_json takes them from there.
	stored := cycle.Plan
	stored.Units = nil
	planJSON, err := json.Marshal(stored)
	if err != nil {
		return ScanCycleRecord{}, err
	}
	tx, err := ss.store.DB.BeginTx(ctx, nil)
	if err != nil {
		return ScanCycleRecord{}, err
	}
	defer tx.Rollback()
	_, err = tx.ExecContext(ctx, `INSERT INTO scan_cycles(id,job_id,job,job_revision,config_hash,execution_hash,baseline_epoch,plan_json,status,attempt_count,no_progress_attempts,total_units,completed_units,total_probes,completed_probes,started_at,updated_at,expires_at,finished_at,last_error) VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)`,
		cycle.ID, cycle.JobID, cycle.Job, cycle.JobRevision, cycle.ConfigHash, cycle.ExecutionHash, cycle.BaselineEpoch, planJSON, cycle.Status, cycle.AttemptCount, cycle.NoProgressAttempts, cycle.TotalUnits, cycle.CompletedUnits, cycle.TotalProbes, cycle.CompletedProbes, sqliteTimestamp(cycle.StartedAt), sqliteTimestamp(cycle.UpdatedAt), sqliteTimestamp(cycle.ExpiresAt), "", cycle.LastError)
	if err != nil {
		return ScanCycleRecord{}, err
	}
	for _, unit := range cycle.Plan.Units {
		raw, marshalErr := json.Marshal(unit)
		if marshalErr != nil {
			return ScanCycleRecord{}, marshalErr
		}
		if _, err = tx.ExecContext(ctx, `INSERT INTO scan_cycle_units(cycle_id,sequence,work_unit_json,identity,phase,probes,status,attempts,snapshot_json,started_at,finished_at,last_error) VALUES(?,?,?,?,?,?,?,?,?,?,?,?)`, cycle.ID, unit.Sequence, raw, scanCycleUnitIdentity(unit), unit.Phase, unit.Probes, "pending", 0, []byte(`{}`), "", "", ""); err != nil {
			return ScanCycleRecord{}, err
		}
	}
	if err = tx.Commit(); err != nil {
		return ScanCycleRecord{}, err
	}
	return cycle, nil
}

// ReconcileScanCycleEnrichment expands a phase-aware Naabu cycle from durable
// discovery checkpoints. Each bounded batch marks its discovery rows in the
// same transaction that creates the corresponding Nmap enrichment work. The
// method drains all available batches, but every transaction is capped by
// scanCycleReconcileBatchSize and can be interrupted by the caller's context.
//
// Dynamic units are authoritative in scan_cycle_units. We deliberately do not
// rewrite the potentially very large plan_json blob for every discovery batch;
// this keeps reconciliation linear in the amount of newly completed evidence.
// GetScanCycle reports the authoritative counters from scan_cycles, while
// LoadScanCycleFragments uses the unit table when promoting a completed cycle.
func (ss *SystemStore) ReconcileScanCycleEnrichment(ctx context.Context, cycleID string) error {
	cycle, err := ss.scanCycle(ctx, cycleID)
	if err != nil {
		return err
	}
	if cycle.Status != "running" && cycle.Status != "paused" && cycle.Status != "stalled" {
		return nil
	}
	if cycle.Plan.Job.TCP == nil || cycle.Plan.Job.TCP.Engine != config.EngineNaabuNmap {
		return nil
	}
	if cycle.Plan, err = ss.scanCyclePlan(ctx, cycleID); err != nil {
		return err
	}

	for {
		if err := ctx.Err(); err != nil {
			return err
		}
		worked, batchErr := ss.reconcileScanCycleEnrichmentBatch(ctx, cycleID, cycle.Plan)
		if batchErr != nil {
			return batchErr
		}
		if !worked {
			return nil
		}
	}
}

// reconcileScanCycleEnrichmentBatch performs one bounded reconciliation
// transaction. The bool reports whether more checkpoint or dynamic work was
// committed and lets the caller drain additional batches without making the
// writer transaction itself unbounded.
func (ss *SystemStore) reconcileScanCycleEnrichmentBatch(ctx context.Context, cycleID string, plan scanner.WorkPlan) (bool, error) {
	tx, err := ss.store.DB.BeginTx(ctx, nil)
	if err != nil {
		return false, err
	}
	defer tx.Rollback()
	var status, cycleJob string
	if err := tx.QueryRowContext(ctx, `SELECT status,job_id FROM scan_cycles WHERE id=?`, cycleID).Scan(&status, &cycleJob); errors.Is(err, sql.ErrNoRows) {
		return false, fmt.Errorf("%w: %s", ErrNoScanCycle, cycleID)
	} else if err != nil {
		return false, err
	}
	if status != "running" && status != "paused" && status != "stalled" {
		return false, tx.Commit()
	}

	// Phase is maintained as an indexed scalar on each unit, so SQLite can
	// count completed discovery rows without invoking JSON1 or loading any
	// checkpoint payload. Only the first bounded batch is decoded below.
	var discoveryCount, completedDiscoveryCount int
	if err := tx.QueryRowContext(ctx, `SELECT COUNT(*),COALESCE(SUM(CASE WHEN status='completed' THEN 1 ELSE 0 END),0) FROM scan_cycle_units WHERE cycle_id=? AND phase='discovery'`, cycleID).Scan(&discoveryCount, &completedDiscoveryCount); err != nil {
		return false, err
	}
	if discoveryCount == 0 {
		return false, tx.Commit()
	}
	discoveryComplete := completedDiscoveryCount == discoveryCount

	type discoveryRow struct {
		sequence int
		unit     scanner.WorkUnit
		snapshot model.Snapshot
	}
	rows, err := tx.QueryContext(ctx, `SELECT u.sequence,u.work_unit_json,u.snapshot_json FROM scan_cycle_units AS u WHERE u.cycle_id=? AND u.status='completed' AND u.phase='discovery' AND NOT EXISTS (SELECT 1 FROM scan_cycle_discovery_checkpoints AS c WHERE c.cycle_id=u.cycle_id AND c.sequence=u.sequence) ORDER BY u.sequence LIMIT ?`, cycleID, scanCycleReconcileBatchSize)
	if err != nil {
		return false, err
	}
	var pending []discoveryRow
	for rows.Next() {
		var row discoveryRow
		var unitRaw, snapshotRaw []byte
		if err := rows.Scan(&row.sequence, &unitRaw, &snapshotRaw); err != nil {
			rows.Close()
			return false, err
		}
		if err := json.Unmarshal(unitRaw, &row.unit); err != nil {
			rows.Close()
			return false, err
		}
		if len(snapshotRaw) > 0 && string(snapshotRaw) != "{}" && string(snapshotRaw) != "null" {
			if err := json.Unmarshal(snapshotRaw, &row.snapshot); err != nil {
				rows.Close()
				return false, err
			}
		}
		pending = append(pending, row)
	}
	if err := rows.Err(); err != nil {
		rows.Close()
		return false, err
	}
	rows.Close()

	// Gather one deterministic port set per effective address from only this
	// batch. Discovery address batches are disjoint; unioning within the batch
	// still protects against duplicate host observations during recovery.
	// Every positive TCP port the job currently tracks (baseline, open
	// incidents, pending and suppressed changes) is included as a bounded
	// safety net: Naabu emits positive discoveries only, so a transient miss
	// must still be confirmed by Nmap before EdgeWatch records a closure.
	portsByAddress := map[string]map[int]struct{}{}
	batchAddresses := map[string]struct{}{}
	for _, row := range pending {
		for _, address := range row.unit.Addresses {
			if normalized := normalizeCycleAddress(address); normalized != "" {
				batchAddresses[normalized] = struct{}{}
			}
		}
		for _, host := range row.snapshot.Hosts {
			if normalized := normalizeCycleAddress(host.Address); normalized != "" {
				batchAddresses[normalized] = struct{}{}
			}
		}
	}
	expectedPorts, expectedErr := expectedTCPPortsTx(ctx, tx, cycleJob, plan.Targets)
	if expectedErr != nil {
		return false, expectedErr
	}
	for address, ports := range expectedPorts {
		if _, inBatch := batchAddresses[address]; !inBatch {
			continue
		}
		if len(ports) == 0 {
			continue
		}
		set := portsByAddress[address]
		if set == nil {
			set = map[int]struct{}{}
			portsByAddress[address] = set
		}
		for port := range ports {
			set[port] = struct{}{}
		}
	}
	for _, row := range pending {
		for _, host := range row.snapshot.Hosts {
			address := normalizeCycleAddress(host.Address)
			if address == "" {
				continue
			}
			for _, protocol := range host.Protocols {
				if protocol.Protocol != "tcp" || protocol.DiscoveryEngine != "naabu" {
					continue
				}
				set := portsByAddress[address]
				if set == nil {
					set = map[int]struct{}{}
					portsByAddress[address] = set
				}
				for _, port := range protocol.DiscoveredPorts {
					if port.Port >= 1 && port.Port <= 65535 {
						set[port.Port] = struct{}{}
					}
				}
			}
		}
	}

	type discoveryGroup struct {
		family    int
		ports     []int
		addresses []string
	}
	groups := map[string]*discoveryGroup{}
	for address, set := range portsByAddress {
		if len(set) == 0 {
			continue
		}
		ports := make([]int, 0, len(set))
		for port := range set {
			ports = append(ports, port)
		}
		sort.Ints(ports)
		family := 4
		if ip := net.ParseIP(address); ip != nil && ip.To4() == nil {
			family = 6
		}
		key := fmt.Sprintf("%d\x00%s", family, formatCyclePorts(ports))
		group := groups[key]
		if group == nil {
			group = &discoveryGroup{family: family, ports: ports}
			groups[key] = group
		}
		group.addresses = append(group.addresses, address)
	}
	groupKeys := make([]string, 0, len(groups))
	for key := range groups {
		groupKeys = append(groupKeys, key)
	}
	sort.Strings(groupKeys)

	var nextSequence int
	if err := tx.QueryRowContext(ctx, `SELECT COALESCE(MAX(sequence),-1)+1 FROM scan_cycle_units WHERE cycle_id=?`, cycleID).Scan(&nextSequence); err != nil {
		return false, err
	}
	var added []scanner.WorkUnit
	newIdentities := make(map[string]struct{})
	factor := boolFactor(plan.Job.TCP.ServiceDetection)
	enrichmentTemplate := plan.Job.TCP.EnrichmentArgs
	if len(enrichmentTemplate) == 0 {
		// Older Naabu profiles used nmap_args for the confirmation command.
		// Match the scanner executor's compatibility fallback so persisted
		// checkpoints never describe a multi-address unit that the template
		// can only render one address for.
		enrichmentTemplate = plan.Job.TCP.NmapArgs
	}
	addressBatchSize := scanner.NmapAddressBatchLimit(enrichmentTemplate)
	for _, key := range groupKeys {
		group := groups[key]
		sort.Strings(group.addresses)
		for addressStart := 0; addressStart < len(group.addresses); addressStart += addressBatchSize {
			addressEnd := addressStart + addressBatchSize
			if addressEnd > len(group.addresses) {
				addressEnd = len(group.addresses)
			}
			addresses := append([]string(nil), group.addresses[addressStart:addressEnd]...)
			perChunk := scanner.MaxWorkUnitPorts
			if capacity := int(scanner.MaxWorkUnitProbes / (int64(len(addresses)) * factor)); capacity > 0 && perChunk > capacity {
				perChunk = capacity
			}
			if perChunk < 1 {
				perChunk = 1
			}
			for portStart := 0; portStart < len(group.ports); portStart += perChunk {
				portEnd := portStart + perChunk
				if portEnd > len(group.ports) {
					portEnd = len(group.ports)
				}
				portChunk := group.ports[portStart:portEnd]
				unit := scanner.WorkUnit{Sequence: nextSequence, Engine: config.EngineNmap, Phase: "enrichment", Protocol: "tcp", Family: group.family, Targets: subsetCycleTargets(plan.Targets, addresses), Addresses: addresses, Ports: formatCyclePorts(portChunk), PortCount: len(portChunk), Probes: int64(len(addresses)) * int64(len(portChunk)) * factor}
				nextSequence++
				identity := scanCycleUnitIdentity(unit)
				if _, exists := newIdentities[identity]; exists {
					continue
				}
				exists, err := scanCycleUnitIdentityExists(ctx, tx, cycleID, identity)
				if err != nil {
					return false, err
				}
				if exists {
					continue
				}
				added = append(added, unit)
				newIdentities[identity] = struct{}{}
			}
		}
	}

	// Only append UDP after the final discovery batch has been checkpointed.
	// Otherwise a large recovery batch could place UDP ahead of enrichment work
	// belonging to later discovery rows.
	morePending := false
	if len(pending) > 0 {
		lastSequence := pending[len(pending)-1].sequence
		if err := tx.QueryRowContext(ctx, `SELECT EXISTS(SELECT 1 FROM scan_cycle_units AS u WHERE u.cycle_id=? AND u.status='completed' AND u.phase='discovery' AND u.sequence>? AND NOT EXISTS (SELECT 1 FROM scan_cycle_discovery_checkpoints AS c WHERE c.cycle_id=u.cycle_id AND c.sequence=u.sequence))`, cycleID, lastSequence).Scan(&morePending); err != nil {
			return false, err
		}
	}
	if discoveryComplete && !morePending && plan.Job.UDP != nil {
		var udpCount int
		if err := tx.QueryRowContext(ctx, `SELECT COUNT(*) FROM scan_cycle_units WHERE cycle_id=? AND phase='udp'`, cycleID).Scan(&udpCount); err != nil {
			return false, err
		}
		if udpCount == 0 {
			for _, unit := range buildCycleUDPUnits(plan, nextSequence) {
				identity := scanCycleUnitIdentity(unit)
				if _, exists := newIdentities[identity]; exists {
					continue
				}
				exists, err := scanCycleUnitIdentityExists(ctx, tx, cycleID, identity)
				if err != nil {
					return false, err
				}
				if exists {
					continue
				}
				added = append(added, unit)
				newIdentities[identity] = struct{}{}
			}
		}
	}

	stamp := sqliteTimestamp(time.Now())
	for _, row := range pending {
		if _, err := tx.ExecContext(ctx, `INSERT OR IGNORE INTO scan_cycle_discovery_checkpoints(cycle_id,sequence,processed_at) VALUES(?,?,?)`, cycleID, row.sequence, stamp); err != nil {
			return false, err
		}
	}
	var addedProbes int64
	for _, unit := range added {
		raw, err := json.Marshal(unit)
		if err != nil {
			return false, err
		}
		if _, err := tx.ExecContext(ctx, `INSERT INTO scan_cycle_units(cycle_id,sequence,work_unit_json,identity,phase,probes,status,attempts,snapshot_json,started_at,finished_at,last_error) VALUES(?,?,?,?,?,?,?,?,?,?,?,?)`, cycleID, unit.Sequence, raw, scanCycleUnitIdentity(unit), unit.Phase, unit.Probes, "pending", 0, []byte(`{}`), "", "", ""); err != nil {
			return false, err
		}
		addedProbes += unit.Probes
	}
	if len(added) > 0 {
		result, err := tx.ExecContext(ctx, `UPDATE scan_cycles SET total_units=total_units+?,total_probes=total_probes+?,updated_at=? WHERE id=? AND status IN ('running','paused','stalled')`, len(added), addedProbes, stamp, cycleID)
		if err != nil {
			return false, err
		}
		if count, _ := result.RowsAffected(); count != 1 {
			return false, ErrCycleNotResumable
		}
	}
	worked := len(pending) > 0 || len(added) > 0
	if err := tx.Commit(); err != nil {
		return false, err
	}
	return worked, nil
}

// expectedTCPPortsTx returns, per effective address, every positive TCP port
// the job's runtime state currently tracks: baseline ports, and the ports of
// open incidents, pending changes and suppressed changes that expect the port
// to be open. Baseline units and changes name a logical target, so targets
// maps a DNS or other logical name to the addresses pinned by the cycle plan.
func expectedTCPPortsTx(ctx context.Context, tx *sql.Tx, jobID string, targets []scanner.ResolvedTarget) (map[string]map[int]struct{}, error) {
	expected := map[string]map[int]struct{}{}
	if strings.TrimSpace(jobID) == "" {
		return expected, nil
	}
	var raw []byte
	if err := tx.QueryRowContext(ctx, `SELECT state_json FROM job_runtime WHERE job_id=?`, jobID).Scan(&raw); errors.Is(err, sql.ErrNoRows) {
		return expected, nil
	} else if err != nil {
		return expected, err
	}
	var state model.JobState
	if err := json.Unmarshal(raw, &state); err != nil {
		// Legacy or corrupt runtime state cannot safely add expected-port work;
		// keep the empty map and let the discovery evidence stand on its own.
		state = model.JobState{}
	}
	targetAddresses := make(map[string][]string, len(targets))
	for _, target := range targets {
		targetAddresses[target.Name] = append(targetAddresses[target.Name], target.Addresses...)
	}
	addTrackedChangeTCPPorts(expected, state, targetAddresses)
	if state.Baseline == nil {
		return expected, nil
	}
	for _, unit := range state.Baseline.Units {
		if !strings.EqualFold(unit.Protocol, "tcp") {
			continue
		}
		var ports []int
		for _, port := range unit.Ports {
			if port.Port >= 1 && port.Port <= 65535 && isPositiveCyclePortState(port.State) {
				ports = append(ports, port.Port)
			}
		}
		if len(ports) == 0 {
			continue
		}
		// A unit stores the addresses its target resolved to when the baseline
		// was scanned, and a legacy unit stores none. A DNS target can resolve
		// elsewhere by now, so its ports are also expected on every address the
		// plan pinned for the target. The caller drops addresses outside the
		// current discovery batch.
		addresses := append(append([]string(nil), unit.Addresses...), targetAddresses[unit.Target]...)
		if len(addresses) == 0 {
			addresses = []string{unit.Target}
		}
		for _, address := range addresses {
			address = normalizeCycleAddress(address)
			if address == "" {
				address = normalizeCycleAddress(unit.Target)
			}
			if address == "" {
				continue
			}
			expectTCPPorts(expected, address, ports...)
		}
	}
	return expected, nil
}

// addTrackedChangeTCPPorts adds the TCP ports that open incidents, pending
// changes and suppressed changes expect to be open. A change carries only its
// logical target, so each target maps to every address the plan pinned for it;
// a target missing from the plan is used only when it is an address itself.
func addTrackedChangeTCPPorts(expected map[string]map[int]struct{}, state model.JobState, targetAddresses map[string][]string) {
	add := func(change model.Change) {
		if !strings.EqualFold(change.Protocol, "tcp") || change.Port < 1 || change.Port > 65535 || !changeExpectsOpenPort(change) {
			return
		}
		addresses := targetAddresses[change.Target]
		if len(addresses) == 0 {
			addresses = []string{change.Target}
		}
		for _, address := range addresses {
			if address = normalizeCycleAddress(address); address != "" {
				expectTCPPorts(expected, address, change.Port)
			}
		}
	}
	for _, incident := range state.Incidents {
		add(incident.Change)
	}
	for _, pending := range state.Pending {
		add(pending.Change)
	}
	for _, change := range state.SuppressedChanges {
		add(change)
	}
}

func expectTCPPorts(expected map[string]map[int]struct{}, address string, ports ...int) {
	set := expected[address]
	if set == nil {
		set = map[int]struct{}{}
		expected[address] = set
	}
	for _, port := range ports {
		set[port] = struct{}{}
	}
}

func isPositiveCyclePortState(state string) bool {
	state = strings.ToLower(strings.TrimSpace(state))
	return state == "open" || state == "open|filtered"
}

// changeExpectsOpenPort reports whether a tracked change claims its port is
// currently open: a port change to a positive state, on the target or on one
// of its addresses, or a service change whose new value is a fingerprint
// rather than the absence of the port.
func changeExpectsOpenPort(change model.Change) bool {
	switch change.Kind {
	case "port", "port-address":
		return isPositiveCyclePortState(change.New)
	case "service":
		value := strings.TrimSpace(change.New)
		return value != "" && value != "not-open"
	default:
		return false
	}
}

